import { chromium } from "@playwright/test";
const prompt = process.argv[2];
const b = await chromium.launch({ channel: "chrome", headless: true });
const pg = await b.newPage({ viewport: { width: 1400, height: 1000 } });
let n = 0;
await pg.route("**/api/llm", async (route) => {
  if (route.request().method() !== "POST") return route.continue();
  const body = JSON.parse(route.request().postData());
  const last = body.messages.at(-1);
  const i = ++n;
  console.log(`\n#${i} IN  [${last.role}] ${String(last.content ?? JSON.stringify(last.tool_calls)).slice(0, 700).replace(/\n/g, "\\n")}`);
  const resp = await route.fetch();
  const text = await resp.text();
  const calls = [...text.matchAll(/event: tool_call\ndata: (.*)\n/g)].map((m) => JSON.parse(m[1]));
  const said = [...text.matchAll(/event: text\ndata: (.*)\n/g)].map((m) => JSON.parse(m[1]).delta).join("");
  console.log(`#${i} OUT text="${said.slice(0, 160).replace(/\n/g, " ")}" calls=[${calls.map((c) => c.name + "(" + c.args.slice(0, 170).replace(/\n/g, "\\n") + ")").join(", ")}]`);
  await route.fulfill({ response: resp, body: text });
});
await pg.goto("http://127.0.0.1:3000/");
await pg.evaluate(() => localStorage.clear());
await pg.reload();
await pg.waitForFunction(() => document.body.innerText.includes("NetLogo Web: ready"), null, { timeout: 30000 });
await pg.fill("textarea", prompt);
await pg.keyboard.press("Enter");
await pg.waitForFunction(() => !document.body.innerText.includes("working…") && document.querySelectorAll("button.font-mono").length > 0, null, { timeout: 420000, polling: 1000 });
await new Promise((r) => setTimeout(r, 1500));
console.log("\n=== NOTICES ===");
console.log((await pg.$$eval(".border-amber-300, .border-green-300", (e) => e.map((x) => x.textContent.slice(0, 260)))).join("\n"));
console.log("chips:", (await pg.$$eval("button.font-mono", (e) => e.map((x) => x.textContent.trim()))).join(" "));
await b.close();
