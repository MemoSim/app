import { chromium } from "@playwright/test";
const prompt = process.argv[2] ?? "Create a predator-prey model with 100 sheep and 20 wolves, with sliders for both and a population plot.";
const b = await chromium.launch({ channel: "chrome", headless: true });
const pg = await b.newPage({ viewport: { width: 1400, height: 1000 } });
pg.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await pg.goto("http://127.0.0.1:3000/");
await pg.waitForFunction(() => document.body.innerText.includes("NetLogo Web: ready"), null, { timeout: 30000 });
await pg.fill("textarea", prompt);
await pg.keyboard.press("Enter");
const t0 = Date.now();
await pg.waitForFunction(() => !document.body.innerText.includes("working…") && document.querySelectorAll("button.font-mono").length > 0, null, { timeout: 240000, polling: 1000 });
await new Promise((r) => setTimeout(r, 1500));
console.log("elapsed s:", ((Date.now() - t0) / 1000).toFixed(0));
const chips = await pg.$$eval("button.font-mono", (els) => els.map((e) => e.textContent.trim()));
console.log("tools:", chips.join(" | "));
const text = await pg.evaluate(() => document.querySelector(".overflow-y-auto").innerText.split("\n").slice(-12).join("\n"));
console.log("--- chat tail ---\n" + text);
await pg.screenshot({ path: "/tmp/nlchat.png" });
await b.close();
