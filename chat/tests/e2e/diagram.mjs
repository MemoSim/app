import assert from "node:assert/strict";
import { chromium } from "playwright";

const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto(`${process.env.BASE_URL ?? "http://127.0.0.1:3001"}/diagram`, { waitUntil: "networkidle" });
  assert.equal(await page.locator('[data-node="stock"]').count(), 3);
  assert.equal(await page.locator('[data-testid="sfd-flow"]').count(), 4);
  assert.equal(await page.locator('[data-testid="sfd-cloud"]').count(), 2);
  assert.equal(await page.locator('[data-node="auxiliary"]').count(), 3);
  async function dragInfluence(from, targetRole) {
    const port = await page.getByTestId(`influence-port-${from}`).boundingBox();
    const target = await page.getByRole("button", { name: targetRole, exact: true }).boundingBox();
    await page.mouse.move(port.x + port.width / 2, port.y + port.height / 2);
    await page.mouse.down();
    await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 10 });
    assert.equal(await page.getByTestId("influence-connection-preview").count(), 1);
    await page.mouse.up();
  }
  const influenceCount = await page.getByTestId("sfd-influence").count();
  await dragInfluence("arrival-rate", "Stock Susceptible");
  assert.equal(await page.getByTestId("sfd-influence").count(), influenceCount + 1);
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  await dragInfluence("arrival-rate", "Auxiliary contact-rate");
  assert.equal(await page.getByTestId("sfd-influence").count(), influenceCount + 1);
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  await dragInfluence("recoveries", "Flow infections");
  assert.equal(await page.getByTestId("sfd-influence").count(), influenceCount + 1);
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  const sourcePort = await page.getByTestId("flow-port-Susceptible-right").boundingBox();
  const destinationStock = await page.getByRole("button", { name: "Stock Infected", exact: true }).boundingBox();
  await page.mouse.move(sourcePort.x + sourcePort.width / 2, sourcePort.y + sourcePort.height / 2);
  await page.mouse.down();
  await page.mouse.move(destinationStock.x + destinationStock.width / 2, destinationStock.y + destinationStock.height / 2, { steps: 12 });
  assert.equal(await page.getByTestId("flow-connection-preview").count(), 1);
  await page.mouse.up();
  assert.equal(await page.locator('[data-testid="sfd-flow"]').count(), 5);
  assert.equal(await page.getByLabel("Flow from").inputValue(), "Susceptible");
  assert.equal(await page.getByLabel("Flow to").inputValue(), "Infected");
  await page.getByRole("button", { name: "Delete element", exact: true }).click();
  assert.equal(await page.locator('[data-testid="sfd-flow"]').count(), 4);
  const palette = page.getByRole("group", { name: "Add diagram elements" });
  assert.equal(await palette.locator("svg[data-sfd-tool]").count(), 6);
  await page.getByRole("button", { name: "+ Source", exact: true }).click();
  assert.equal(await page.getByLabel("Flow from").inputValue(), "outside");
  assert.equal(await page.getByLabel("Flow to").inputValue(), "Susceptible");
  await page.getByRole("button", { name: "Close element editor" }).click();
  const dropTarget = page.getByRole("img", { name: "Susceptible → Infected → Recovered" });
  const targetBox = await dropTarget.boundingBox();
  const dataTransfer = await page.evaluateHandle(() => new DataTransfer());
  await page.getByRole("button", { name: "+ Stock", exact: true }).dispatchEvent("dragstart", { dataTransfer });
  await dropTarget.dispatchEvent("drop", { dataTransfer, clientX: targetBox.x + targetBox.width / 2, clientY: targetBox.y + targetBox.height / 2 });
  assert.equal(await page.locator('[data-node="stock"]').count(), 4);
  assert.equal(await page.getByLabel("Element name").inputValue(), "stock-1");
  await page.getByRole("button", { name: "Delete element", exact: true }).click();
  assert.equal(await page.locator('[data-node="stock"]').count(), 3);
  await page.getByRole("button", { name: "+ Sink", exact: true }).click();
  assert.equal(await page.getByLabel("Flow to").inputValue(), "outside");
  await page.getByRole("button", { name: "Close element editor" }).click();
  await page.getByRole("button", { name: "Stock Susceptible", exact: true }).click();
  await page.getByRole("form", { name: "Element editor" }).waitFor();
  assert.equal(await page.getByLabel("Element equation").inputValue(), "990");
  await page.getByRole("button", { name: "Close element editor" }).click();
  const svg = page.getByRole("img", { name: "Susceptible → Infected → Recovered" });
  const initial = await svg.getAttribute("viewBox");
  await page.getByRole("button", { name: "Zoom in", exact: true }).click();
  assert.notEqual(await svg.getAttribute("viewBox"), initial);
  await page.getByRole("button", { name: "Fit", exact: true }).click();
  assert.equal(await svg.getAttribute("viewBox"), initial);
  await page.getByRole("button", { name: "+ Auxiliary", exact: true }).click();
  await page.getByLabel("Element name").fill("policy-factor");
  await page.getByLabel("Element equation").fill("2");
  await page.getByRole("button", { name: "Save element", exact: true }).click();
  assert.equal(await page.locator('[data-node="auxiliary"]').count(), 4);
  await page.getByLabel("Element name").fill("contact-rate");
  await page.getByRole("button", { name: "Save element", exact: true }).click();
  await page.getByRole("alert").filter({ hasText: /Duplicate name/ }).waitFor();
  assert.equal(await page.locator('[data-node="auxiliary"]').count(), 4);
  await page.getByLabel("Element name").fill("policy-factor");
  await page.getByRole("button", { name: "Delete element", exact: true }).click();
  assert.equal(await page.locator('[data-node="auxiliary"]').count(), 3);
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  assert.equal(await page.locator('[data-node="auxiliary"]').count(), 4);
  await page.getByRole("button", { name: "Redo", exact: true }).click();
  assert.equal(await page.locator('[data-node="auxiliary"]').count(), 3);
  await page.getByRole("button", { name: "Connect stocks", exact: true }).click();
  await page.getByRole("button", { name: "Stock Recovered", exact: true }).click();
  await page.getByRole("button", { name: "Stock Susceptible", exact: true }).click();
  await page.getByLabel("Element name").fill("waning-immunity");
  await page.getByLabel("Element equation").fill("Recovered * 0.01");
  await page.getByRole("button", { name: "Save element", exact: true }).click();
  assert.equal(await page.locator('[data-testid="sfd-flow"]').count(), 5);
  await page.getByRole("button", { name: "Close element editor" }).click();
  const stock = page.getByRole("button", { name: "Stock Infected", exact: true });
  const originalRect = await stock.locator("rect").getAttribute("y");
  const stockBox = await stock.boundingBox();
  await page.mouse.move(stockBox.x + 30, stockBox.y + 20);
  await page.mouse.down();
  await page.mouse.move(stockBox.x + 30, stockBox.y + 70, { steps: 8 });
  await page.mouse.up();
  assert.notEqual(await stock.locator("rect").getAttribute("y"), originalRect);
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export JSON", exact: true }).click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), "memosim-system-dynamics.json");
  await page.getByLabel("Simulation timestep").fill("0.05");
  await page.getByRole("button", { name: "Check structure", exact: true }).click();
  await page.getByText("Structure is valid.", { exact: false }).waitFor();
  await page.getByRole("tab", { name: "Equations", exact: true }).click();
  await page.getByRole("heading", { name: "Model equations · dt = 0.05", exact: true }).waitFor();
  await page.getByRole("tab", { name: "Diagram", exact: true }).click();
  await page.locator("summary").filter({ hasText: "Influence links (" }).click();
  await page.getByLabel("Influence source").selectOption("arrival-rate");
  await page.getByLabel("Influence target").selectOption("recoveries");
  await page.getByRole("button", { name: "Add influence", exact: true }).click();
  await page.getByRole("button", { name: "Remove influence arrival-rate to recoveries", exact: true }).waitFor();
  await page.getByRole("button", { name: "Remove influence arrival-rate to recoveries", exact: true }).click();
  await page.getByRole("button", { name: "Derive from equations", exact: true }).click();
  await page.locator("summary").filter({ hasText: "Influence links (" }).click();
  await page.getByRole("button", { name: "Flow recoveries", exact: true }).click();
  await page.getByLabel("Reversible flow").check();
  await page.getByRole("button", { name: "Save element", exact: true }).click();
  await page.getByRole("button", { name: "Close element editor", exact: true }).click();
  await page.locator("summary").filter({ hasText: "Simulation controls & results" }).click();
  assert.equal(await page.getByRole("button", { name: "Setup", exact: true }).isDisabled(), true);
  await page.locator("summary").filter({ hasText: "Simulation controls & results" }).click();
  await page.getByRole("tab", { name: "Generated procedures", exact: true }).click();
  await page.getByText("Apply the draft first to view matching compiler-generated procedures.", { exact: false }).waitFor();
  await page.getByRole("tab", { name: "Diagram", exact: true }).click();
  const nativeDownloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export model", exact: true }).click();
  assert.equal((await nativeDownloadPromise).suggestedFilename(), "memosim-system-dynamics.nlogox");
  const editedBounds = await svg.getAttribute("viewBox");
  assert.ok(await page.locator('[data-testid="sfd-influence"]').count() > 0);
  await page.getByRole("button", { name: /Influence links/ }).click();
  assert.equal(await page.locator('[data-testid="sfd-influence"]').count(), 0);
  await page.getByRole("button", { name: /Influence links/ }).click();
  const box = await svg.boundingBox();
  await page.mouse.move(box.x + box.width - 50, box.y + box.height - 50);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width - 150, box.y + box.height - 100);
  await page.mouse.up();
  assert.notEqual(await svg.getAttribute("viewBox"), editedBounds);
  await page.getByRole("button", { name: "Fit", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  assert.deepEqual(errors, []);
  console.log("PASS: SFD rendering, element editing, collision validation, add/delete, undo/redo, connect stocks, node dragging, JSON export, zoom/fit/pan, influence toggle, mobile width; no browser errors");
} finally {
  await browser.close();
}
